/**
 * Build the browser half of `@dsh/comfyui`.
 *
 * esbuild bundles `client/index.js` into one CommonJS chunk, which is then
 * wrapped in dsh's `window.__ModuleLoader__.load({ id, factory })` envelope so
 * the Web GUI can register it like any shipped client plugin.
 *
 * Install the package dev dependencies before building.
 */
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL('../', import.meta.url));

/** Resolution candidates for esbuild, in order. */
const ESBUILD_CANDIDATES = [
  'esbuild',
  resolve(root, 'node_modules/esbuild'),
];

/**
 * Load esbuild from the first candidate that resolves.
 * @returns the esbuild module namespace.
 */
function loadEsbuild() {
  const failures = [];
  for (const candidate of ESBUILD_CANDIDATES) {
    try {
      const loaded = require(candidate);
      if (loaded !== null && typeof loaded === 'object' && typeof loaded.build === 'function') return loaded;
      failures.push(`${candidate}: no build() export`);
    } catch (error) {
      failures.push(`${candidate}: ${error.code ?? error.message}`);
    }
  }
  throw new Error(`无法加载 esbuild（已尝试 ${ESBUILD_CANDIDATES.length} 个位置）：\n  ${failures.join('\n  ')}`);
}

/** Package id used in the ModuleLoader envelope and by every registration. */
const PLUGIN_ID = '@dsh/comfyui';

/** Modules dsh's ModuleLoader supplies to a client plugin. */
const EXTERNALS = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/dsh-client-ui-primitives',
];

/**
 * Wrap a bundled CommonJS chunk in the ModuleLoader envelope.
 * @param code the bundled body.
 * @returns the loadable module text.
 */
function wrap(code) {
  return `// Generated by scripts/build.mjs for ${PLUGIN_ID}; do not edit.
window.__ModuleLoader__.load({
  id: '${PLUGIN_ID}',
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  }
});
`;
}

async function main() {
  const esbuild = loadEsbuild();
  const result = await esbuild.build({
    absWorkingDir: root,
    entryPoints: ['client/index.js'],
    bundle: true,
    write: false,
    platform: 'browser',
    format: 'cjs',
    target: ['chrome100'],
    external: EXTERNALS,
    jsx: 'transform',
    // `client/index.js` is the required entry filename but carries one inline
    // SVG component, so `.js` must be parsed with the JSX loader.
    loader: { '.js': 'jsx' },
    legalComments: 'none',
    logLevel: 'warning',
    charset: 'utf8',
  });
  const output = result.outputFiles?.[0]?.text;
  if (typeof output !== 'string' || output === '') throw new Error('esbuild 没有产出任何内容');
  const text = wrap(output);
  const outfile = resolve(root, 'lib/client.js');
  await mkdir(dirname(outfile), { recursive: true });
  await writeFile(outfile, text, 'utf8');
  const kb = (Buffer.byteLength(text, 'utf8') / 1024).toFixed(1);
  console.log(`Built ${PLUGIN_ID} client → lib/client.js (${kb} kB, esbuild ${esbuild.version})`);
}

main().catch((error) => {
  console.error(`[comfyui] 构建失败：${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
});
